CREATE TABLE station (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uq_station_name UNIQUE (name)
);

CREATE TABLE line (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10)  NOT NULL,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uq_line_code UNIQUE (code)
);

CREATE TABLE line_station (
    line_id     BIGINT       NOT NULL,
    station_id  BIGINT       NOT NULL,
    rank        SMALLINT     NOT NULL,
    distance_km NUMERIC(6,1) NOT NULL,
    CONSTRAINT pk_line_station PRIMARY KEY (line_id, station_id),
    CONSTRAINT uq_line_station_rank UNIQUE (line_id, rank),
    CONSTRAINT fk_line_station_line FOREIGN KEY (line_id) REFERENCES line (id) ON DELETE CASCADE,
    CONSTRAINT fk_line_station_station FOREIGN KEY (station_id) REFERENCES station (id) ON DELETE RESTRICT,
    CONSTRAINT ck_line_station_rank CHECK (rank > 0),
    CONSTRAINT ck_line_station_distance CHECK (distance_km >= 0)
);

CREATE TABLE service_calendar (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    monday     BOOLEAN     NOT NULL DEFAULT FALSE,
    tuesday    BOOLEAN     NOT NULL DEFAULT FALSE,
    wednesday  BOOLEAN     NOT NULL DEFAULT FALSE,
    thursday   BOOLEAN     NOT NULL DEFAULT FALSE,
    friday     BOOLEAN     NOT NULL DEFAULT FALSE,
    saturday   BOOLEAN     NOT NULL DEFAULT FALSE,
    sunday     BOOLEAN     NOT NULL DEFAULT FALSE,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    CONSTRAINT uq_service_calendar_name UNIQUE (name),
    CONSTRAINT ck_service_calendar_dates CHECK (end_date >= start_date)
);

CREATE TABLE calendar_exception (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_calendar_id BIGINT  NOT NULL,
    exception_date      DATE    NOT NULL,
    is_running          BOOLEAN NOT NULL,
    CONSTRAINT uq_calendar_exception_date UNIQUE (service_calendar_id, exception_date),
    CONSTRAINT fk_calendar_exception_calendar FOREIGN KEY (service_calendar_id) REFERENCES service_calendar (id) ON DELETE CASCADE
);

CREATE TABLE train (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number              VARCHAR(10) NOT NULL,
    line_id             BIGINT      NOT NULL,
    service_calendar_id BIGINT      NOT NULL,
    CONSTRAINT uq_train_number UNIQUE (number),
    CONSTRAINT fk_train_line FOREIGN KEY (line_id) REFERENCES line (id) ON DELETE RESTRICT,
    CONSTRAINT fk_train_calendar FOREIGN KEY (service_calendar_id) REFERENCES service_calendar (id) ON DELETE RESTRICT
);

CREATE TABLE stop (
    train_id       BIGINT   NOT NULL,
    rank           SMALLINT NOT NULL,
    station_id     BIGINT   NOT NULL,
    arrival_time   TIME,
    departure_time TIME,
    CONSTRAINT pk_stop PRIMARY KEY (train_id, rank),
    CONSTRAINT uq_stop_station UNIQUE (train_id, station_id),
    CONSTRAINT fk_stop_train FOREIGN KEY (train_id) REFERENCES train (id) ON DELETE CASCADE,
    CONSTRAINT fk_stop_station FOREIGN KEY (station_id) REFERENCES station (id) ON DELETE RESTRICT,
    CONSTRAINT ck_stop_rank CHECK (rank > 0),
    CONSTRAINT ck_stop_has_time CHECK (arrival_time IS NOT NULL OR departure_time IS NOT NULL),
    CONSTRAINT ck_stop_dwell CHECK (arrival_time IS NULL OR departure_time IS NULL OR departure_time >= arrival_time)
);

CREATE FUNCTION check_stop_sequence() RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM stop s
        JOIN stop n ON n.train_id = s.train_id AND n.rank = s.rank + 1
        WHERE s.train_id = NEW.train_id
          AND n.arrival_time < s.departure_time
    ) THEN
        RAISE EXCEPTION 'train %: arrival at a stop is before departure from the previous stop', NEW.train_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_stop_sequence
    AFTER INSERT OR UPDATE ON stop
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_stop_sequence();

