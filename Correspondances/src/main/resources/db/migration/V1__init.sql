CREATE TABLE passenger (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50)  NOT NULL,
    last_name  VARCHAR(50)  NOT NULL,
    email      VARCHAR(255) NOT NULL,
    CONSTRAINT uq_passenger_email UNIQUE (email)
);

CREATE TABLE booking (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id   BIGINT        NOT NULL,
    train_run_id   BIGINT        NOT NULL,
    seat_id        BIGINT        NOT NULL,
    fare_id        BIGINT        NOT NULL,
    departure_rank SMALLINT      NOT NULL,
    arrival_rank   SMALLINT      NOT NULL,
    price          NUMERIC(8,2)  NOT NULL,
    booked_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_booking_run_seat UNIQUE (id, train_run_id, seat_id),
    CONSTRAINT fk_booking_passenger FOREIGN KEY (passenger_id) REFERENCES passenger (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_train_run FOREIGN KEY (train_run_id) REFERENCES train_run (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_seat FOREIGN KEY (seat_id) REFERENCES seat (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_fare FOREIGN KEY (fare_id) REFERENCES fare (id) ON DELETE RESTRICT,
    CONSTRAINT ck_booking_departure_rank CHECK (departure_rank > 0),
    CONSTRAINT ck_booking_segment CHECK (arrival_rank > departure_rank),
    CONSTRAINT ck_booking_price CHECK (price >= 0)
);

CREATE TABLE booking_segment (
    train_run_id BIGINT   NOT NULL,
    seat_id      BIGINT   NOT NULL,
    segment_rank SMALLINT NOT NULL,
    booking_id   BIGINT   NOT NULL,
    CONSTRAINT pk_booking_segment PRIMARY KEY (train_run_id, seat_id, segment_rank),
    CONSTRAINT fk_booking_segment_booking FOREIGN KEY (booking_id, train_run_id, seat_id)
        REFERENCES booking (id, train_run_id, seat_id) ON DELETE CASCADE,
    CONSTRAINT ck_booking_segment_rank CHECK (segment_rank > 0)
);

CREATE FUNCTION create_booking_segments() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO booking_segment (train_run_id, seat_id, segment_rank, booking_id)
    SELECT b.train_run_id, b.seat_id, s.segment_rank, b.id
    FROM new_bookings b
    CROSS JOIN LATERAL generate_series(b.departure_rank, b.arrival_rank - 1) AS s(segment_rank);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_booking_segments
    AFTER INSERT ON booking
    REFERENCING NEW TABLE AS new_bookings
    FOR EACH STATEMENT EXECUTE FUNCTION create_booking_segments();

CREATE FUNCTION forbid_booking_trip_update() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'booking %: trip cannot be modified, cancel and rebook instead', OLD.id
        USING ERRCODE = 'check_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_booking_trip_immutable
    BEFORE UPDATE OF train_run_id, seat_id, departure_rank, arrival_rank ON booking
    FOR EACH ROW EXECUTE FUNCTION forbid_booking_trip_update();
